"""Structured XLSX export of the investigation package.

Reuses the exact same scoped data builder as the PDF (RBAC, vocabulary and
the ground-truth firewall inherited). Secondary to the PDF: same sections,
tabular form. Missing data renders as "Not available"."""
import io

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from sqlalchemy.orm import Session

from app.models import User
from app.reports.investigation_report import DISCLAIMER, NA, build_report_data

HEADER_FILL = PatternFill("solid", fgColor="EEF2FF")
HEADER_FONT = Font(bold=True, color="312E81")


def _sheet(wb: Workbook, title: str, header: list[str], rows: list[list]):
    ws = wb.create_sheet(title)
    ws.append(header)
    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
    for row in rows:
        ws.append([NA if v is None or v == "" else v for v in row])
    for i, col in enumerate(ws.columns, 1):
        width = max((len(str(c.value)) for c in col if c.value is not None), default=8)
        ws.column_dimensions[col[0].column_letter].width = min(max(width + 2, 10), 60)
    return ws


def render_xlsx(data: dict) -> bytes:
    wb = Workbook()
    wb.remove(wb.active)
    c, p, r = data["case"], data["project"], data["risk"]
    bd = c.get("priority_breakdown") or {}

    _sheet(wb, "Summary", ["Field", "Value"], [
        ["Case number", c["case_number"]],
        ["Generated at", data["generated_at"].strftime("%Y-%m-%d %H:%M UTC")],
        ["Generated by", data["generated_by"]],
        ["Dataset version", data["dataset_version"]],
        ["Status", c["status"]],
        ["Opened by", c["opened_by"]],
        ["Assigned officer", c["assigned_to"]],
        ["SLA due", str(c["sla_due_at"] or "")],
        ["Priority at open", c["priority_score"]],
        ["Priority formula", bd.get("formula")],
        ["Reason for investigation", data["opening_reason"]],
        ["Outcome", c["outcome"]],
        ["Outcome note", c["outcome_note"]],
        ["Case summary", c["summary"]],
        ["Summary provenance", data["summary_provenance"]],
        ["Project code", p["code"]],
        ["Project title", p["title"]],
        ["District / State", f"{p['district']}, {p['state']}"],
        ["Constituency", p["constituency"]],
        ["Responsible-AI notice", DISCLAIMER],
    ])

    _sheet(wb, "Financials", ["Field", "Value"], [
        ["Recommended cost", p["recommended_cost"]],
        ["Sanctioned cost", p["sanctioned_cost"]],
        ["Revised cost", p["revised_cost"]],
        ["Expenditure", p["expenditure"]],
        ["Physical progress %", p["physical_progress_pct"]],
        ["Financial progress %", p["financial_progress_pct"]],
        ["Sanction no.", p.get("sanction_no")],
        ["Sanction date", str(p.get("sanction_date") or "")],
        ["Reconciliation status", (data["reconciliation"] or {}).get("status")],
        ["Reconciliation mismatch", (data["reconciliation"] or {}).get("mismatch_amount")],
    ])

    _sheet(wb, "Risk Factors",
           ["Factor", "Contribution", "Severity", "Explanation", "Source ref"],
           [[f["factor_type"], f["contribution"], f["severity"], f["explanation"],
             f["source_ref"]] for f in (r["factors"] if r else [])]
           or [["No current risk assessment", None, None, None, None]])

    _sheet(wb, "Anomalies", ["Detector", "Score", "Severity", "Explanation"],
           [[a["detector"], a["score"], a["severity"], a["explanation"]]
            for a in data["anomalies"]] or [["None recorded", None, None, None]])

    _sheet(wb, "Investigation Actions",
           ["When", "Action", "By", "Reason", "From", "To"],
           [[str(a["created_at"]), a["action_type"], a["user"], a["reason"],
             a["from_status"], a["to_status"]] for a in data["actions"]])

    _sheet(wb, "Audit Trail", ["When", "Source", "Actor", "Event"],
           [[str(e["timestamp"]), e["source"], e["actor"], e["action"]]
            for e in data["audit"]])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def generate(db: Session, user: User, investigation_id: int) -> tuple[bytes, str]:
    data = build_report_data(db, user, investigation_id)
    return render_xlsx(data), data["case"]["case_number"]
