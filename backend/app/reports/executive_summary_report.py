"""Executive Summary PDF — built from dashboard_service.executive_summary().

Uses ReportLab (same dependency as investigation_report.py). All data comes
from the same backend aggregation that powers the Command Center modal — zero
hardcoded numbers. Missing sections render as "Not available".
"""
from datetime import timezone
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)
from sqlalchemy.orm import Session

from app.models import User
from app.services import dashboard_service, misc_service

# ── Colours (match institutional palette) ────────────────────────────────────
NAVY    = colors.HexColor("#0b1220")
ACCENT  = colors.HexColor("#1a56db")
MUTED   = colors.HexColor("#5a7290")
BORDER  = colors.HexColor("#d1d9e3")
RED     = colors.HexColor("#dc2626")
ORANGE  = colors.HexColor("#ea580c")
GREEN   = colors.HexColor("#047857")
WARN_BG = colors.HexColor("#fffbeb")
WARN_FG = colors.HexColor("#92400e")

NA = "Not available"

DISCLAIMER = (
    "This Executive Summary is a decision-support document generated by the "
    "DRISHTI AI Risk & Intelligence Platform. Risk scores and anomaly signals "
    "are decision-support indicators, not findings of fraud, misconduct, or guilt. "
    "All determinations remain with authorized officials."
)


# ── Styles ────────────────────────────────────────────────────────────────────
def _styles():
    ss = getSampleStyleSheet()
    base = dict(fontName="Helvetica", leading=11)
    return {
        "cover_platform": ParagraphStyle(
            "cp", parent=ss["BodyText"], fontSize=7.5, textColor=MUTED,
            fontName="Helvetica", spaceAfter=2, letterSpacing=1),
        "cover_title": ParagraphStyle(
            "ct", parent=ss["Title"], fontSize=20, textColor=NAVY,
            fontName="Helvetica-Bold", spaceAfter=4),
        "cover_meta": ParagraphStyle(
            "cm", parent=ss["BodyText"], fontSize=8, textColor=MUTED,
            fontName="Helvetica", leading=12),
        "h2": ParagraphStyle(
            "h2", parent=ss["Heading2"], fontSize=10.5, textColor=NAVY,
            fontName="Helvetica-Bold", spaceBefore=12, spaceAfter=3,
            borderPad=0),
        "body": ParagraphStyle(
            "b", parent=ss["BodyText"], fontSize=8.5, leading=12,
            fontName="Helvetica"),
        "body_bold": ParagraphStyle(
            "bb", parent=ss["BodyText"], fontSize=8.5, leading=12,
            fontName="Helvetica-Bold"),
        "small": ParagraphStyle(
            "s", parent=ss["BodyText"], fontSize=7.5, leading=10,
            textColor=MUTED, fontName="Helvetica"),
        "disclaimer": ParagraphStyle(
            "disc", parent=ss["BodyText"], fontSize=7.5, leading=10.5,
            textColor=WARN_FG, fontName="Helvetica", backColor=WARN_BG,
            borderPad=4),
        "situation": ParagraphStyle(
            "sit", parent=ss["BodyText"], fontSize=9, leading=13.5,
            fontName="Helvetica"),
    }


# ── Helpers ───────────────────────────────────────────────────────────────────
def _crore(n):
    if n is None:
        return NA
    return f"Rs {n / 1e7:,.2f} Cr"


def _pct(n):
    return f"{n}%" if n is not None else NA


def _int(n):
    return f"{int(n):,}" if n is not None else NA


def _kv(pairs, st, key_width=55 * mm):
    rows = [
        [Paragraph(f"<b>{k}</b>", st["body"]),
         Paragraph(str(v) if v is not None else NA, st["body"])]
        for k, v in pairs
    ]
    t = Table(rows, colWidths=[key_width, None])
    t.setStyle(TableStyle([
        ("VALIGN",       (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW",    (0, 0), (-1, -2), 0.35, BORDER),
        ("TOPPADDING",   (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 2.5),
    ]))
    return t


def _grid(header, rows, st, widths=None):
    data = [[Paragraph(f"<b>{h}</b>", st["small"]) for h in header]]
    for r in rows:
        data.append([Paragraph(str(c) if c is not None else "—", st["small"]) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("VALIGN",       (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND",   (0, 0), (-1, 0), colors.HexColor("#eef2ff")),
        ("GRID",         (0, 0), (-1, -1), 0.35, BORDER),
        ("TOPPADDING",   (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 2.5),
    ]))
    return t


def _risk_colour(level):
    l = (level or "low").lower()
    return {
        "critical": RED,
        "high":     ORANGE,
        "moderate": colors.HexColor("#d97706"),
        "low":      MUTED,
    }.get(l, MUTED)


# ── Footer / header ───────────────────────────────────────────────────────────
def _footer(canvas, doc, scope, generated_at):
    canvas.saveState()
    canvas.setFont("Helvetica", 6.5)
    canvas.setFillColor(MUTED)
    left = (
        f"DRISHTI · National Risk & Intelligence Platform — "
        f"Executive Summary · Scope: {scope.upper()} · "
        f"Generated: {generated_at}"
    )
    canvas.drawString(15 * mm, 10 * mm, left)
    canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


# ── Main PDF builder ──────────────────────────────────────────────────────────
def render_pdf(data: dict) -> bytes:
    st = _styles()
    buf = BytesIO()

    scope = (data.get("scope") or "national").upper()
    gen_ts = data.get("generated_at", "")
    try:
        from datetime import datetime
        gen_ts_fmt = datetime.fromisoformat(gen_ts).strftime("%Y-%m-%d %H:%M UTC")
    except Exception:
        gen_ts_fmt = str(gen_ts)[:16]

    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=16 * mm, rightMargin=16 * mm,
        topMargin=16 * mm, bottomMargin=18 * mm,
        title="DRISHTI Executive Summary",
        author="DRISHTI Platform",
    )

    def footer_cb(canvas, doc):
        _footer(canvas, doc, scope, gen_ts_fmt)

    el = []
    ov   = data.get("overview") or {}
    risk = data.get("risk") or {}
    sig  = data.get("signals") or {}
    pri  = data.get("priority_projects") or []
    sts  = data.get("top_risk_states") or []
    alts = data.get("recent_alerts") or []

    # ── Cover ─────────────────────────────────────────────────────────────────
    el.append(Paragraph("DRISHTI · National Risk &amp; Intelligence Platform",
                         st["cover_platform"]))
    el.append(Spacer(1, 4))
    el.append(Paragraph("Executive Summary", st["cover_title"]))
    el.append(Spacer(1, 2))
    el.append(Paragraph(
        f"<b>Scope:</b> {scope} &nbsp;&nbsp; <b>Generated:</b> {gen_ts_fmt} &nbsp;&nbsp; "
        f"<b>Dataset note:</b> {data.get('dataset_note', 'Prototype Dataset — Synthetic Data')}",
        st["cover_meta"],
    ))
    el.append(Spacer(1, 6))
    el.append(Paragraph(DISCLAIMER, st["disclaimer"]))
    el.append(Spacer(1, 10))

    # ── 1. Executive Situation ────────────────────────────────────────────────
    el.append(Paragraph("1. Executive Situation", st["h2"]))
    crit  = risk.get("critical_count", 0)
    highr = risk.get("high_risk_count", 0)
    alerts_n = sig.get("open_alerts", 0)
    sit_text = (
        f"The MPLADS portfolio under this scope contains "
        f"<b>{_int(ov.get('total_projects'))}</b> projects with a total sanctioned "
        f"outlay of <b>{_crore(ov.get('total_sanctioned'))}</b>. "
        f"Current fund utilization stands at <b>{_pct(ov.get('utilization_pct'))}</b> "
        f"({_crore(ov.get('total_expenditure'))} expended)."
    )
    if crit:
        sit_text += (
            f" <b>{crit} critical-risk project{'s' if crit != 1 else ''}</b> "
            f"require immediate attention."
        )
    if highr:
        sit_text += (
            f" <b>{highr} high-risk project{'s' if highr != 1 else ''}</b> "
            f"are under elevated monitoring."
        )
    if alerts_n:
        sit_text += (
            f" <b>{_int(alerts_n)} active alert{'s' if alerts_n != 1 else ''}</b> "
            f"are currently open."
        )
    el.append(Paragraph(sit_text, st["situation"]))
    el.append(Spacer(1, 4))

    # ── 2. Key Risk Indicators ────────────────────────────────────────────────
    el.append(Paragraph("2. Key Risk Indicators", st["h2"]))
    el.append(_kv([
        ("Critical Risk Projects",  _int(risk.get("critical_count"))),
        ("High Risk Projects",       _int(risk.get("high_risk_count"))),
        ("Moderate Risk Projects",   _int(risk.get("moderate_count"))),
        ("Low Risk Projects",        _int(risk.get("low_count"))),
        ("Open Alerts",              _int(sig.get("open_alerts"))),
        ("Data Quality Issues",      _int(sig.get("data_quality_issues"))),
    ], st))
    el.append(Spacer(1, 4))

    # ── 3. AI Anomaly Signals ─────────────────────────────────────────────────
    anom = sig.get("anomaly_counts") or {}
    if anom:
        el.append(Paragraph("3. AI Anomaly Signals", st["h2"]))
        el.append(_grid(
            ["Signal Type", "Projects Affected"],
            [[k.replace("_", " ").title(), _int(v)] for k, v in anom.items()],
            st, widths=[110 * mm, None],
        ))
        el.append(Paragraph(
            "Anomaly signals are AI-generated indicators for review — not findings of wrongdoing.",
            st["small"],
        ))
        el.append(Spacer(1, 4))

    # ── 4. Financial Position ─────────────────────────────────────────────────
    el.append(Paragraph("4. Financial Position", st["h2"]))
    el.append(_kv([
        ("Total Sanctioned",            _crore(ov.get("total_sanctioned"))),
        ("Total Expenditure Released",  _crore(ov.get("total_expenditure"))),
        ("Utilization Rate",            _pct(ov.get("utilization_pct"))),
        ("Unspent Balance",             _crore(ov.get("unspent_balance"))),
        ("Delayed / At-Risk Projects",  _int(ov.get("delayed_projects"))),
    ], st))
    el.append(Spacer(1, 4))

    # ── 5. Priority Review Queue ──────────────────────────────────────────────
    if pri:
        el.append(Paragraph("5. Priority Review Queue", st["h2"]))
        rows = [
            [
                f"{p.get('risk_score') or '—'} / {(p.get('risk_level') or 'low').upper()}",
                f"{p.get('code', '')} — {(p.get('title') or '')[:70]}",
                f"{p.get('district', '')}, {p.get('state', '')}",
                _crore(p.get("sanctioned_cost")),
            ]
            for p in pri
        ]
        el.append(_grid(
            ["Risk Score / Level", "Project", "Location", "Sanctioned"],
            rows, st,
            widths=[28 * mm, 80 * mm, 38 * mm, None],
        ))
        el.append(Spacer(1, 4))

    # ── 6. State Performance ──────────────────────────────────────────────────
    if sts:
        el.append(Paragraph("6. State Performance (by Risk Exposure, top 5)", st["h2"]))
        rows = [
            [
                s.get("state") or s.get("state_name") or NA,
                f"{s.get('avg_risk') or '—'}",
                f"{s.get('utilization_pct') or '—'}%",
                str(s.get("critical_count") or 0),
                _int(s.get("project_count")),
            ]
            for s in sts
        ]
        el.append(_grid(
            ["State", "Avg Risk Score", "Utilization", "Critical", "Projects"],
            rows, st,
            widths=[50 * mm, 30 * mm, 28 * mm, 22 * mm, None],
        ))
        el.append(Spacer(1, 4))

    # ── 7. Recent Alerts ──────────────────────────────────────────────────────
    if alts:
        el.append(Paragraph("7. Recent High-Priority Alerts", st["h2"]))
        rows = [
            [
                (a.get("severity") or "—").upper(),
                f"{a.get('risk_score') or '—'}",
                a.get("reason") or "—",
                f"{a.get('project_code', '')} · {a.get('district', '')}, {a.get('state', '')}",
            ]
            for a in alts
        ]
        el.append(_grid(
            ["Severity", "Risk Score", "Reason", "Project · Location"],
            rows, st,
            widths=[20 * mm, 20 * mm, 70 * mm, None],
        ))
        el.append(Spacer(1, 4))

    # ── Closing disclaimer ────────────────────────────────────────────────────
    el.append(Spacer(1, 8))
    el.append(Paragraph(DISCLAIMER, st["disclaimer"]))

    doc.build(el, onFirstPage=footer_cb, onLaterPages=footer_cb)
    return buf.getvalue()


# ── Public entry point ────────────────────────────────────────────────────────
def generate(db: Session, user: User) -> bytes:
    """Collect data and render; auditing is done by the caller (dashboard.py)."""
    data = dashboard_service.executive_summary(db, user)
    return render_pdf(data)
